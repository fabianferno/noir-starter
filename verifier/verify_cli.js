#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { program } = require('commander');
const { spawnSync } = require('child_process');

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function verifySignature(rootHex, signatureBase64, publicKeyPem, hashAlg = 'sha256') {
  const verifier = crypto.createVerify(hashAlg);
  const rootBuffer = Buffer.from(rootHex.replace(/^0x/, ''), 'hex');
  verifier.update(rootBuffer);
  verifier.end();
  const signature = Buffer.from(signatureBase64, 'base64');
  return verifier.verify(publicKeyPem, signature);
}

function runBbVerify(bbBin, proofPath, vkPath, publicPath) {
  const args = ['verify', '-p', proofPath, '-k', vkPath];
  if (publicPath) {
    args.push('--public-inputs', publicPath);
  }
  const result = spawnSync(bbBin, args, { stdio: 'inherit' });
  if (result.error) {
    throw result.error;
  }
  if (result.status !== 0) {
    throw new Error(`bb verify failed with code ${result.status}`);
  }
}

program
  .requiredOption('-b, --bundle <path>', 'Path to bundle.json produced by merkle builder')
  .option('-s, --signature <path>', 'Path to base64-encoded signature file')
  .option('-p, --proof <path>', 'Path to proof file generated by Barretenberg')
  .option('-k, --vk <path>', 'Path to Barretenberg verifying key file')
  .option('--public <path>', 'Path to public inputs JSON (defaults to alongside proof)')
  .option('--pubkey <path>', 'Path to PEM-encoded public key for TPM signature verification')
  .option('--bb-bin <path>', 'Barretenberg CLI binary (defaults to bb on PATH)', 'bb')
  .option('--hash-alg <algo>', 'Hash algorithm used for TPM signature (default sha256)', 'sha256')
  .option('--skip-proof', 'Skip SNARK proof verification step')
  .parse(process.argv);

const opts = program.opts();
const bundle = readJson(opts.bundle);
const rootHex = bundle.root_hex || bundle.root || (() => { throw new Error('bundle missing root_hex or root'); })();

console.log(`[verify_cli] Loaded bundle for root ${rootHex}`);

if (opts.signature) {
  if (!opts.pubkey) {
    throw new Error('Signature verification requested but --pubkey not provided');
  }
  const signatureBase64 = fs.readFileSync(opts.signature, 'utf8').trim();
  const pubkey = fs.readFileSync(opts.pubkey, 'utf8');
  const ok = verifySignature(rootHex, signatureBase64, pubkey, opts.hashAlg);
  if (!ok) {
    throw new Error('TPM signature verification failed');
  }
  console.log('[verify_cli] TPM signature verification: OK');
} else {
  console.log('[verify_cli] TPM signature verification skipped');
}

if (!opts.skipProof) {
  if (!opts.proof || !opts.vk) {
    throw new Error('Proof verification requested but --proof or --vk missing');
  }
  const publicPath = opts.public || path.join(path.dirname(opts.proof), 'real_frame_proof.public.json');
  console.log(`[verify_cli] Running bb verify using ${opts.proof}`);
  runBbVerify(opts.bbBin, opts.proof, opts.vk, publicPath);
  console.log('[verify_cli] SNARK proof verification: OK');
} else {
  console.log('[verify_cli] SNARK proof verification skipped');
}

console.log('[verify_cli] All selected checks passed');
